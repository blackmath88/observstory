// Copies the production build into frontend/release/, the prebuilt bundle the Action ships.
// Consumers never need Node: the Action copies these files beside its data/ output.
//   npm run release
import { cpSync, existsSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const from = join(root, "dist", "client");
const to = join(root, "release");
if (!existsSync(join(from, "index.html"))) throw new Error("run `vite build` first: dist/client/index.html is missing");
if (existsSync(join(from, "data"))) throw new Error("the build must not contain data/: the Action writes it per run");
rmSync(to, { recursive: true, force: true });
cpSync(from, to, { recursive: true });
writeFileSync(
  join(to, "README.md"),
  "# Prebuilt Observatory frontend\n\nGenerated by `npm run release` in `frontend/`. Do not edit by hand.\nThe Action copies these files into its output when `frontend: observatory` is set (ADR-038).\n",
);
console.log(`release: ${readdirSync(join(to, "assets")).length} assets → frontend/release/`);
